BRAND = colors.HexColor("#0F4C5C")
INK = colors.HexColor("#121A24")
MUTED = colors.HexColor("#4A5664")
LINE = colors.HexColor("#E1E6EA")
CANVAS = colors.HexColor("#F3F5F7")
NOT_AVAILABLE = "Not available yet"

styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=styles["Heading1"], fontName="Helvetica-Bold", fontSize=17, leading=21, textColor=INK,
                    spaceAfter=2)
H2 = ParagraphStyle("h2", parent=styles["Heading2"], fontName="Helvetica-Bold", fontSize=12, leading=15, textColor=BRAND,
                    spaceBefore=12, spaceAfter=5)
BODY = ParagraphStyle("body", parent=styles["BodyText"], fontName="Helvetica", fontSize=9.5, textColor=INK, leading=12.5)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8.5, leading=11, textColor=MUTED)
NUM = ParagraphStyle("num", parent=BODY, alignment=TA_RIGHT)
TH = ParagraphStyle("th", parent=BODY, fontName="Helvetica-Bold", fontSize=8.5, leading=11, textColor=colors.white)
TH_NUM = ParagraphStyle("thn", parent=TH, alignment=TA_RIGHT)
KPI_LABEL = ParagraphStyle("kpil", parent=SMALL, fontSize=8)
KPI_VALUE = ParagraphStyle("kpiv", parent=BODY, fontName="Helvetica-Bold", fontSize=11.5, leading=14)
ZEBRA = colors.HexColor("#F7F9FA")


def pkr(value) -> str:
    if value is None:
        return NOT_AVAILABLE
    return f"PKR {Decimal(value):,.2f}"


def status_label(s):
    return (s or "").replace("_", " ").title()


class NumberedCanvas(canvas.Canvas):
    """Brand bar on every page, audience label, and a 'Page x of y' footer once the page count is known."""

    AUDIENCE = "Official record"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self._decorate(total)
            super().showPage()
        super().save()

    def _decorate(self, total):
        w, h = A4
        self.setFillColor(BRAND)
        self.rect(0, h - 16 * mm, w, 16 * mm, stroke=0, fill=1)
        self.setFillColor(colors.white)
        self.setFont("Helvetica-Bold", 13)
        self.drawString(15 * mm, h - 10 * mm, "Aab o Hisaab AI")
        self.setFont("Helvetica", 8.5)
        self.drawString(15 * mm, h - 13.6 * mm, "PDMA Punjab - Disaster relief funds")
        self.setFont("Helvetica-Bold", 9)
        self.drawRightString(w - 15 * mm, h - 10 * mm, self.AUDIENCE)
        self.setStrokeColor(LINE)
        self.setLineWidth(0.6)
        self.line(15 * mm, 14 * mm, w - 15 * mm, 14 * mm)
        self.setFillColor(MUTED)
        self.setFont("Helvetica", 8)
        self.drawString(15 * mm, 9 * mm, "System-generated by Aab o Hisaab AI from verified records. No signature required.")
        self.drawRightString(w - 15 * mm, 9 * mm, f"Page {self._pageNumber} of {total}")


def canvas_for(audience):
    """Canvas class whose header names the document's audience (e.g. 'Donor report', 'NGO statement')."""

    class _Canvas(NumberedCanvas):
        AUDIENCE = audience

    return _Canvas


def _table(header, rows, widths, numeric_cols=(), totals=None):
    """Data table: brand header bar, zebra rows, right-aligned numbers, optional bold totals row."""
    data = [[Paragraph(h, TH_NUM if i in numeric_cols else TH) for i, h in enumerate(header)]]
    for r in rows:
        data.append([Paragraph(str(v), NUM if i in numeric_cols else BODY) for i, v in enumerate(r)])
    empty = len(data) == 1
    if empty:
        data.append([Paragraph("No records in this period.", SMALL)] + [""] * (len(header) - 1))
    if totals and not empty:
        data.append([Paragraph(f"<b>{v}</b>", NUM if i in numeric_cols else BODY) for i, v in enumerate(totals)])
    t = Table(data, colWidths=widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), BRAND),
        ("LINEBELOW", (0, 1), (-1, -1), 0.3, LINE),
        ("BOX", (0, 0), (-1, -1), 0.5, LINE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(2, len(data), 2):
        style.append(("BACKGROUND", (0, i), (-1, i), ZEBRA))
    if empty:
        style.append(("SPAN", (0, 1), (-1, 1)))
    if totals and not empty:
        style += [("BACKGROUND", (0, -1), (-1, -1), CANVAS), ("LINEABOVE", (0, -1), (-1, -1), 0.8, BRAND)]
    t.setStyle(TableStyle(style))
    return t


def _key_values(pairs, widths=(60 * mm, 120 * mm)):
    t = Table([[Paragraph(k, SMALL), Paragraph(f"<b>{v}</b>", BODY)] for k, v in pairs], colWidths=widths)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), CANVAS), ("BOX", (0, 0), (-1, -1), 0.5, LINE),
        ("LINEBELOW", (0, 0), (-1, -1), 0.3, LINE), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6)]))
    return t


def _kpis(pairs, per_row=4):
    """Row(s) of summary boxes: label above, bold value below."""
    cells = [[Paragraph(k, KPI_LABEL), Paragraph(v, KPI_VALUE)] for k, v in pairs]
    rows = [cells[i:i + per_row] for i in range(0, len(cells), per_row)]
    rows[-1] += [""] * (per_row - len(rows[-1]))
    w = 180 * mm / per_row
    t = Table(rows, colWidths=[w] * per_row)
    style = [("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 6),
             ("BOTTOMPADDING", (0, 0), (-1, -1), 6), ("LEFTPADDING", (0, 0), (-1, -1), 7)]
    for r, row in enumerate(rows):
        for c, cell in enumerate(row):
            if cell:
                style += [("BOX", (c, r), (c, r), 0.5, LINE), ("BACKGROUND", (c, r), (c, r), CANVAS)]
    t.setStyle(TableStyle(style))
    return t


def _generated(generated_utc, seconds=False):
    fmt = "%d %b %Y %H:%M:%S PKT" if seconds else "%d %b %Y %H:%M PKT"
    return (datetime.fromisoformat(generated_utc) + timedelta(hours=5)).strftime(fmt)


def _summary(s):
    pairs = [
        ("Total donated", pkr(s["total_donated"])),
        ("Total verified donations", pkr(s["total_verified"])),
        ("Total allocated", pkr(s["total_allocated"])),
        ("Reserved for NGO allocations (not yet sent)", pkr(s.get("total_reserved", "0"))),
        ("Actually disbursed", pkr(s.get("total_disbursed", "0"))),
        ("Total spent", pkr(s["total_spent"]) if s.get("spent_available") else NOT_AVAILABLE),
        ("Remaining (unallocated) balance", pkr(s["remaining_balance"])),
    ]
    if "unspent_allocated" in s:
        pairs.append(("Unspent allocated balance",
                      pkr(s["unspent_allocated"]) if s.get("spent_available") else NOT_AVAILABLE))
    pairs += [("Contributions", s["contributions_count"]), ("Donation batches", s["batches_count"])]
    return _kpis([(k, str(v)) for k, v in pairs], per_row=3)


def _header(story, title, report, period_label, reference, generated_utc):
    generated = _generated(generated_utc)
    story += [
        Paragraph(title, H1),
        Spacer(1, 3 * mm),
        _key_values([("Donor", report["donor"]), ("Reporting period", period_label),
                     ("Report reference", reference), ("Generated", generated)]),
        Paragraph("Financial summary", H2),
    ]


def _build(story, title, audience="Donor report - Confidential to the named donor"):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=24 * mm,
                            bottomMargin=20 * mm, title=title, author="Aab o Hisaab AI")
    doc.build(story, canvasmaker=canvas_for(audience))
    return buf.getvalue()


def _utilization(story, report):
    """'Utilization of your donations': each actual disbursement traced to the contribution and batch it came from."""
    story.append(Paragraph("Utilization of your donations", H2))
    rows = [u for u in report.get("utilization", []) if Decimal(u["disbursed_amount"]) > 0]
    if not rows:
        story.append(Paragraph("No money from these contributions has been disbursed yet.", BODY))
        return
    story.append(_table(
        ["NGO / recipient", "Request", "Allocation", "Batch", "Contribution", "Allocated", "Disbursed", "Date"],
        [[u["ngo_name"] or u["recipient_type"], u["ngo_request_no"] or "—", u["allocation_document_no"], u["batch_no"],
          u["contribution_document_no"], pkr(u["allocated_amount"]), pkr(u["disbursed_amount"]),
          (u["disbursement_date"] or "")[:10] or "—"] for u in rows],
        [27 * mm, 24 * mm, 24 * mm, 24 * mm, 24 * mm, 20 * mm, 20 * mm, 17 * mm], numeric_cols=(5, 6),
    ))


def spent_cell(v):
    return pkr(v) if v is not None else NOT_AVAILABLE


