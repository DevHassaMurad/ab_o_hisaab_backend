"""Donor report PDFs (ReportLab). Built only from report dicts produced by controller/donor_reports.py,
which are scoped to the signed-in donor. Layout: branded header, report details, financial summary,
detail tables, "Page x of y" footer. Amounts in PKR with thousands separators."""
import io
