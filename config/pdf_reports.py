def receipt_voucher_pdf(v, generated_utc):
    """A4 DONATION RECEIPT VOUCHER for one donor donation, built only from database values (see DonorLedger.voucher_data)."""
    label, colour, message = VOUCHER_STATUS[v["payment_status"]]
    generated = _generated(generated_utc, seconds=True)
    verified_on = ((datetime.fromisoformat(v["verification_date"]) + timedelta(hours=5)).strftime("%d %b %Y")
                   if v["verification_date"] and v["payment_status"] != "pending" else "—")
    status_style = ParagraphStyle("status", parent=BODY, fontName="Helvetica-Bold", fontSize=11, textColor=colour)
    amount_style = ParagraphStyle("amt", parent=H1, fontSize=20, textColor=INK)
    head = Table([[Paragraph("DONATION RECEIPT VOUCHER", H1), Paragraph(label, status_style)]],
                 colWidths=[120 * mm, 60 * mm])
    head.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("ALIGN", (1, 0), (1, 0), "RIGHT"),
                              ("LINEBELOW", (0, 0), (-1, 0), 1.2, BRAND), ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
    pairs = [
        ("Receipt number", v["receipt_no"]), ("Donation reference", v["document_no"]),
        ("Donation batch", v["batch_no"]), ("Donor name", v["donor"]), ("Donation date", v["date"]),
        ("Payment method", v["payment_method"] or "Not provided"),
        ("Payment reference", v["payment_reference"] or "Not provided"),
        ("Verification status", label.title()), ("Verification date", verified_on),
    ]
    if v.get("rejection_reason"):
        pairs.append(("Reason", v["rejection_reason"]))
    story = [
        head, Spacer(1, 6 * mm),
        Paragraph("Amount", SMALL), Paragraph(pkr(v["amount"]), amount_style), Spacer(1, 4 * mm),
        _key_values(pairs, widths=(55 * mm, 125 * mm)), Spacer(1, 6 * mm),
        Paragraph(message, BODY), Spacer(1, 10 * mm),
        Paragraph(f"System-generated on {generated} by Aab o Hisaab AI. This voucher is valid without a signature; "
                  f"verify it with receipt number {v['receipt_no']}.", SMALL),
    ]
    return _build(story, f"Donation receipt {v['receipt_no']}", "Donation receipt voucher")


LEDGER_TYPES = {
    "donor_donation": "Donor donation", "campaign_contribution": "Campaign contribution",
    "disbursement": "Transfer to NGO", "transfer_received": "Received from PDMA", "expenditure": "Expenditure",
    "beneficiary_payment": "Beneficiary payment",
}


def _esc(v):
    return str(v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def ledger_pdf(ledger, owner, generated_utc):
    """Funds ledger (PDMA or one NGO): credits, debits and running balance, oldest first, with period totals."""
    p = ledger["period"]
    period = f"{p['from'] or 'Start of records'} to {p['to'] or 'today'}"
    entries = list(reversed(ledger["all"]))
    rows = []
    for e in entries:
        desc = _esc(e["description"])
        if e.get("counterparty"):
            desc += f'<br/><font color="#4A5664" size="8">{_esc(e["counterparty"])}</font>'
        rows.append([(e["at"] + timedelta(hours=5)).strftime("%d %b %Y"), e["reference"] or "-",
                     LEDGER_TYPES.get(e["type"], status_label(e["type"])), desc,
                     pkr(e["debit"]) if e["debit"] else "", pkr(e["credit"]) if e["credit"] else "", pkr(e["balance"])])
    story = [
        Paragraph(_esc(ledger["title"]), H1), Spacer(1, 3 * mm),
        _key_values([("Account", _esc(owner)), ("Period", period), ("Generated", _generated(generated_utc))]),
        Paragraph("Summary", H2),
        _kpis([("Opening balance", pkr(ledger["opening_balance"])), ("Total credit (in)", pkr(ledger["total_credit"])),
               ("Total debit (out)", pkr(ledger["total_debit"])), ("Closing balance", pkr(ledger["closing_balance"]))]),
        Paragraph("Entries", H2),
        _table(["Date", "Reference", "Type", "Description", "Debit", "Credit", "Balance"], rows,
               [19 * mm, 27 * mm, 24 * mm, 42 * mm, 22 * mm, 22 * mm, 24 * mm], numeric_cols=(4, 5, 6),
               totals=["", "", "", "Period totals", pkr(ledger["total_debit"]), pkr(ledger["total_credit"]),
                       pkr(ledger["closing_balance"])]),
        Spacer(1, 4 * mm),
        Paragraph("Credit = money received into this account. Debit = money paid out. Balance is cumulative and "
                  "includes everything before the period (opening balance).", SMALL),
    ]
    if ledger.get("pending_transfers") and Decimal(ledger["pending_transfers"]) > 0:
        story.append(Paragraph(f"Transfers recorded but not yet sent ({pkr(ledger['pending_transfers'])}) are not "
                               "included until they are sent.", SMALL))
    return _build(story, ledger["title"], "Funds ledger - Official record")



