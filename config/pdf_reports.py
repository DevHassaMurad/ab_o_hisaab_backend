def batch_pdf(report, reference, generated_utc):
    story = []
    period = report["donations"][0]["date"] if report["donations"] else "No contributions yet"
    if len(report["donations"]) > 1:
        period = f"{report['donations'][0]['date']} to {report['donations'][-1]['date']}"
    _header(story, f"Batch report · {report['batch_no']}", report, period, reference, generated_utc)
    story.append(_summary(report["summary"]))
    if report.get("request"):
        r = report["request"]
        story += [Paragraph("PDMA request", H2), _key_values([
            ("Request", r["document_no"]), ("Reason", r["reason"]), ("Requested amount", pkr(r["requested_amount"])),
            ("Your response", status_label(r["donor_response"]))])]
    story += [
        Paragraph("Donation details", H2),
        _table(["Batch", "Date", "Document no", "Amount", "Verification"],
               [[d["batch_no"], d["date"], d["document_no"], pkr(d["amount"]), status_label(d["verification_status"])]
                for d in report["donations"]], [35 * mm, 25 * mm, 40 * mm, 40 * mm, 40 * mm], numeric_cols=(3,)),
        Paragraph("Allocation details", H2),
        _table(["Reference", "Date", "Amount", "Purpose", "Recipient", "Status"],
               [[a["reference"], a["date"], pkr(a["amount"]), a["purpose"] or "—",
                 a["ngo_name"] or a["recipient_type"], status_label(a["status"])] for a in report["allocations"]],
               [30 * mm, 20 * mm, 27 * mm, 50 * mm, 33 * mm, 20 * mm], numeric_cols=(2,)),
        Paragraph("Expenditure details", H2),
    ]
    if report["expenditure_available"]:
        story.append(_table(["Reference", "Date", "Purpose", "Amount", "Evidence", "Verification"],
                            [[e["reference"], e["date"], e["purpose"], pkr(e["amount"]), e["evidence_reference"] or "—",
                              status_label(e["verification_status"])] for e in report["expenditures"]],
                            [27 * mm, 20 * mm, 50 * mm, 27 * mm, 34 * mm, 22 * mm], numeric_cols=(3,)))
    else:
        story.append(Paragraph(f"{NOT_AVAILABLE}. NGOs have not reported expenditure against this batch.", BODY))
    _utilization(story, report)
    return _build(story, f"Batch report {report['batch_no']}")


